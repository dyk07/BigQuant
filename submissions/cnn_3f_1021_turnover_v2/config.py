# ======================================================================
# 随机种子 (Python / NumPy / PyTorch 全部固定, 保证可复现)
# ======================================================================
SEED = 42

# ======================================================================
# 数据与窗口
# ======================================================================
FREQS = ["bar30m", "bar15m", "bar5m"]   # 三频 (由 bar1m 内部重采样得到)
LOOKBACK_MINUTES = 120           # 输入窗口回看时长 (分钟)
HORIZON_MINUTES = 30             # 预测未来 30 分钟 VWAP
SAMPLE_STEP_MINUTES = 30         # 日内采样网格 (09:25 + 整/半点)
INPUT_SAME_DAY_ONLY = False      # 输入窗口允许向前回看 (标签窗口仍严格当日)

# 训练区间 (数据只到 2024-12; 2024 年数据用于验证, 不参与最终训练)
TRAIN_MONTHS = [f"{y}{m:02d}" for y in range(2020, 2024) for m in range(1, 13)]

# ======================================================================
# 模型结构超参 (CNN 滑窗 + Transformer)
# ======================================================================
MODEL_CFG = dict(
    in_dim=25,            # 7 个 K 线特征 + 18 个盘口特征
    hidden=64,            # 卷积 / Transformer 隐藏维
    conv_blocks=3,        # 膨胀卷积残差块数 (dilation 1, 2, 4)
    kernel=3,             # 卷积核大小
    transformer_layers=2,  # TransformerEncoder 层数 (Pre-LN)
    heads=4,              # 多头注意力头数
    dropout=0.2,
    fused_dim=64,         # 融合 / head 隐含维
)

# ======================================================================
# 训练超参
# ======================================================================
TRAIN_CFG = dict(
    epochs=12,            # 最大 epoch
    lr=1e-3,              # Adam 初始学习率
    weight_decay=1e-5,
    batch_size=4096,
    patience=4,           # 早停 patience (监控验证集 IC)
    grad_clip=1.0,        # 梯度裁剪 max_norm
    val_months=2,         # 末尾 N 个月作为验证集
    lr_factor=0.5,        # ReduceLROnPlateau 衰减系数
    lr_patience=2,        # ReduceLROnPlateau patience
    loss="corr",          # 1 - Pearson (配合 rank 目标 = soft-IC)
    target="rank",        # 截面 rank 目标 -> [-1, 1]
)

# ======================================================================
# 混合精度训练 (AMP, 自动混合精度)
# ----------------------------------------------------------------------
# 训练/推理前向用 fp16 (GradScaler 回退), 显存减半、吞吐显著提升,
# 是把全量重训压进平台 3 小时上限的关键。数值上 loss 在 fp32 计算,
# 只让模型前向走 fp16, 训练稳定性有保障。CPU / 无 CUDA 时自动失效。
# ======================================================================
USE_AMP = True            # 是否启用 AMP 混合精度训练
AMP_DTYPE = "float16"     # 前向精度: "float16" (需 GradScaler) / "bfloat16"

# ======================================================================
# 截面交叉注意力 (多频融合表示上的跨股票上下文)
# ----------------------------------------------------------------------
# 在融合表示 z 上做同截面内股票间 self-attention, 让股票学习相对强弱。
# 用 block-diagonal mask 限制注意力只在同 (day, minute) 截面内,
# 因此在随机大 batch 下也保持截面语义正确, 不引入未来信息。
# ======================================================================
USE_XSEC = False          # 是否启用截面交叉注意力 (换手 λ 扫描实验: 关闭以隔离变量)
XSEC_LAYERS = 1           # 交叉注意力 Transformer 块数
XSEC_HEADS = 4            # 交叉注意力头数

# ======================================================================
# 换手正则 (信号时序平滑, 降低调仓成本)
# ----------------------------------------------------------------------
# 评分标准中换手率占 20% (换手越低排名越高)。这里惩罚同一只股票在
# 相邻可用截面 (同一交易日、按 SAMPLE_STEP_MINUTES 网格的下一截面) 的
# 预测分数变化: loss = 1 - corr(p_t, p_{t+1})。分数跨截面相关越高,
# 相对排序越稳定、调仓成本越低。该相关形同主损失 (soft-IC) 的量纲,
# 因此权重无需按分数尺度校准。
# ======================================================================
USE_TURNOVER = True       # 是否启用换手正则
LAMBDA_TURNOVER = 0.005   # 换手正则权重 (λ 扫描最优: 相对 corr 主损失; loss = 1 - corr)
TURNOVER_FORM = "corr"    # 换手 loss 形式: corr/zsq/zabs/corr_zsq/corr_zabs
TURNOVER_ALPHA = 1.0      # 混合形式 (corr_zsq/corr_zabs) 中幅度项权重
